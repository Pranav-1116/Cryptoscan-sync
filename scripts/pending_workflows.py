#!/usr/bin/env python3
"""Generate and check the repository's two scheduled-evidence workflows.

`scripts/restore_drill.py` (guide 184) and `scripts/accuracy_ground_truth.py` (guide 185) are the
evidence. Neither runs unless something schedules it, and the schedule lives in
`.github/workflows/`; publishing workflow changes needs a GitHub identity with the required
permission. Files in a branch are not evidence that a scheduled run occurred.

The workflows are generated here: committed, diffable, and covered by
`scripts/tests/test_pending_workflows.py`, which asserts the properties that make them meaningful
rather than a golden string — the schedule, the recovery database, the gate command, the artifact
that survives a failure, and the absence of `|| true`.

    python scripts/pending_workflows.py --stdout                 # read both
    python scripts/pending_workflows.py --write                  # .github/workflows/ (needs scope)
    python scripts/pending_workflows.py --write --into .pending  # stage them for a reviewer

Both workflows prove the mechanism runs against a disposable estate built inside the run. They do
not prove a bank's backups restore, or that a bank's estate scans at 95% — those are the bank's
drills, with the same scripts and the bank's own data. The receipts say so.
"""

from __future__ import annotations

import argparse
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKFLOW_DIR = ROOT / ".github" / "workflows"

#: Weekly, Monday 02:20 UTC: after the Sunday backup window, before the working week, and off the
#: top of the hour when every other scheduled job in the estate starts.
DRILL_SCHEDULE = "20 2 * * 1"
#: The accuracy gate follows the drill, so a week's regression is caught before anyone quotes the
#: number in a review.
ACCURACY_SCHEDULE = "40 2 * * 1"

#: A Fernet key over 32 known bytes. It protects a database that exists for ninety minutes inside
#: a CI runner and is destroyed with the runner, so it is published on purpose: a secret in a
#: workflow file would be a real secret in a public file, and this key has nothing to protect.
CI_ONLY_ENCRYPTION_KEY = base64.urlsafe_b64encode(b"0123456789abcdef0123456789abcdef").decode()
CI_ONLY_SIGNING_SECRET = "ci-only-drill-signing-secret-not-a-production-secret"

COMMON_PYTHONPATH = ":".join((
    "services/api", "services/cbom", "services/dashboard", "services/database", "services/evidence",
    "services/governance", "services/identity", "services/policy", "services/runtime",
    "services/scanner", "services/worker", "shared/shared_config", "shared/shared_models",
    "scripts",
))

RESTORE_DRILL = """\
# Generated by `scripts/pending_workflows.py --write`. Do not edit by hand.
#
# Item 14 of the review: an automated restore drill that restores into
# CRYPTOSCAN_RESTORE_TARGET_DB, measures what came back, and keeps the hash-chained receipt as a
# year-long artifact. What it proves is that the drill runs: the estate it restores is built and
# destroyed in the same run. A bank's own drill uses the same script against its own backups.
name: Restore drill

on:
  schedule:
    - cron: "{schedule}"
  push:
    branches: ['arena/bb4b80dd-cryproscan']
  workflow_dispatch:
    inputs:
      reason:
        description: why this drill is being run now
        required: false

permissions:
  contents: read

concurrency:
  group: restore-drill
  cancel-in-progress: false

jobs:
  drill:
    name: restore, measure, keep the receipt
    runs-on: ubuntu-latest
    timeout-minutes: 45
    services:
      postgres:
        image: postgres:16
        env:
          POSTGRES_USER: drill
          POSTGRES_PASSWORD: drill
          POSTGRES_DB: cryptoscan
        ports: ["5432:5432"]
        options: >-
          --health-cmd "pg_isready -U drill" --health-interval 5s
          --health-timeout 5s --health-retries 20
    env:
      PGPASSWORD: drill
      PG_BIN: /usr/lib/postgresql/16/bin
      CRYPTOSCAN_CI_DISPOSABLE_DB: "1"
      DATABASE_URL: postgresql://drill:drill@localhost:5432/cryptoscan
      # The drill refuses a target that is not named like a recovery database and a target equal
      # to the source. Both refusals are exercised by this job's configuration.
      CRYPTOSCAN_RESTORE_TARGET_DB: postgresql://drill:drill@localhost:5432/restore_drill
      CRYPTOSCAN_BACKUP_DIR: ${{{{ github.workspace }}}}/.drill-backups
      # Published on purpose: it protects a database that exists for one CI run.
      BACKUP_ENCRYPTION_KEY: "{encryption_key}"
      BACKUP_SIGNING_SECRET: "{signing_secret}"
      PYTHONPATH: "{pythonpath}"
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
        with:
          persist-credentials: false
      - uses: actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065 # v5
        with:
          python-version: "3.11"
      - name: Install
        run: |
          python -m pip install -r requirements.txt -c requirements.lock.txt
          sudo apt-get update && sudo apt-get install -y postgresql-client-16
      - name: Build a disposable estate and an empty recovery database
        run: |
          psql "$DATABASE_URL" -c "CREATE DATABASE restore_drill"
          bash scripts/run_migrations.sh
          # Rows the drill can compare. Without them every count is zero on both sides, a restore
          # that produced nothing compares equal to the source, and the drill passes on nothing.
          python scripts/restore_drill_seed.py
      - name: Take a backup, restore it, measure what came back
        run: |
          python scripts/restore_drill.py \\
            --backup-dir "$CRYPTOSCAN_BACKUP_DIR" \\
            --database-id cryptoscan \\
            --create-backup \\
            --out drill-receipt.json \\
            --history .drill-history.jsonl
      - name: Upload the receipt and the chain
        if: always()
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4
        with:
          name: restore-drill-receipt
          path: |
            drill-receipt.json
            .drill-history.jsonl
          retention-days: 365
          if-no-files-found: error
"""

ACCURACY_GATE = """\
# Generated by `scripts/pending_workflows.py --write`. Do not edit by hand.
#
# Guide 185: the accuracy programme as a gate rather than a dashboard somebody regenerates when
# they feel like it. It scores the fact rule against the committed answer key *and* against last
# week's numbers, so a release cannot trade precision for a richer-looking BOM without failing
# here. `--naive` is run too: if the shortcut ever passes, the corpus has stopped distinguishing
# honest scanning from confident guessing and the measurement has become decorative.
name: Accuracy gate

on:
  schedule:
    - cron: "{schedule}"
  push:
    branches: ['arena/bb4b80dd-cryproscan']
  workflow_dispatch:
  pull_request:
    paths:
      - "services/cbom/cbom/accuracy*.py"
      - "services/cbom/cbom/facts.py"
      - "scripts/accuracy_ground_truth.py"
      - "docs/bank-environment/185-*"

permissions:
  contents: read

jobs:
  gate:
    name: score the rule, fail on a regression
    runs-on: ubuntu-latest
    timeout-minutes: 20
    env:
      PYTHONPATH: "{pythonpath}"
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
        with:
          persist-credentials: false
      - uses: actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065 # v5
        with:
          python-version: "3.11"
      - name: Install
        run: |
          python -m pip install -r requirements.txt -c requirements.lock.txt
      - name: The published targets, with no regression against the committed baseline
        run: |
          python scripts/accuracy_ground_truth.py \\
            --baseline docs/bank-environment/185-accuracy-ground-truth.json \\
            --json accuracy-report.json \\
            --md accuracy-dashboard.md \\
            --gate
      - name: The shortcut must still fail
        run: |
          # This step is expected to exit non-zero. It fails the job if it does not: a green
          # `collector -> CBOM` score means the corpus stopped containing the hard cases.
          if python scripts/accuracy_ground_truth.py --naive --gate; then
            echo "the shortcut now passes; the corpus no longer distinguishes guessing" >&2
            exit 1
          fi
      - name: The harness's own tests
        run: python -m pytest scripts/tests/test_accuracy_ground_truth.py services/cbom/tests/test_accuracy.py services/cbom/tests/test_facts.py -q
      - name: Upload the report
        if: always()
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4
        with:
          name: accuracy-report
          path: |
            accuracy-report.json
            accuracy-dashboard.md
          if-no-files-found: warn
"""


def render_restore_drill(schedule: str = DRILL_SCHEDULE) -> str:
    return RESTORE_DRILL.format(schedule=schedule, encryption_key=CI_ONLY_ENCRYPTION_KEY,
                                signing_secret=CI_ONLY_SIGNING_SECRET,
                                pythonpath=COMMON_PYTHONPATH)


def render_accuracy_gate(schedule: str = ACCURACY_SCHEDULE) -> str:
    return ACCURACY_GATE.format(schedule=schedule, pythonpath=COMMON_PYTHONPATH)


WORKFLOWS = {
    "restore-drill.yml": render_restore_drill,
    "accuracy-gate.yml": render_accuracy_gate,
}


def rendered() -> dict[str, str]:
    return {name: render() for name, render in WORKFLOWS.items()}


def write(into: Path | None = None) -> list[Path]:
    directory = into or WORKFLOW_DIR
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, body in rendered().items():
        path = directory / name
        path.write_text(body, encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true",
                        help=f"write to {WORKFLOW_DIR.relative_to(ROOT)} "
                             "(publication may need workflow-write permission)")
    parser.add_argument("--into", default=None,
                        help="write the files into this directory instead (e.g. .pending)")
    parser.add_argument("--stdout", action="store_true", help="print both workflows")
    args = parser.parse_args(argv)

    if args.stdout:
        for name, body in rendered().items():
            print(f"# ---- {name} ----")
            print(body, end="")
        return 0
    if not args.write and not args.into:
        parser.print_help()
        return 2
    for path in write(Path(args.into) if args.into else None):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
