"""Render the eleven-plane correlation register, from the measured register.

Two axes are shown per plane and they are not interchangeable: whether the shipped
correlator *cites* a fact from the plane (measured by running it) and whether a
collector here can *supply* one (measured by importing the producer). The document is
generated so it cannot describe a build it was not rendered from.

    python scripts/gen_attack_planes.py --write
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "bank-environment" / "106-attack-correlation-planes.md"


def render(document: dict) -> str:
    counts = document["counts"]
    resolution = document["resolution"]
    lines = [
        "# Attack correlation: the eleven evidence planes",
        "",
        "Generated by `scripts/gen_attack_planes.py --write` from",
        "`shared_models/attack_planes.py`. Do not edit by hand; regenerate and read the",
        "diff.",
        "",
        "*\"Complete attack correlation\"* is the product vision's phrase for joining static",
        "inventory, runtime observation, network evidence, certificates, HSM, KMS, identity,",
        "configuration, SBOM, CBOM and temporal behaviour into one picture. Eleven names in a",
        "slide is not that. Two things are measured per plane, and they fail differently:",
        "",
        "- **reading** — whether the correlator cites a fact from the plane. Measured by",
        "  running `attack_patterns.correlate` with a canonical statement from that plane and",
        "  asking whether the plane appears in a pattern it emitted.",
        "- **supply** — whether a collector in this build produces such facts. Measured by",
        "  importing the `module:attribute` that would produce them.",
        "",
        "| Measure | Count |",
        "|---|---|",
        f"| Planes | {counts['planes']} |",
        f"| Read (correlator cites a fact) | {counts['consumed']} |",
        f"| Supplied (a producer imports) | {counts['supplied']} |",
        f"| **Correlated** (both) | **{counts['correlated']}** |",
        f"| Independent witnesses (can corroborate) | {counts['corroborating']} |",
        f"| Blind (one axis missing) | {counts['blind']} |",
        "",
        "## The planes",
        "",
        "| Plane | Reading | Supply | Witness | Asserts |",
        "|---|---|---|---|---|",
    ]
    for row in document["planes"]:
        lines.append(
            f"| **{row['label']}** (`{row['id']}`) | {row['reading']} | {row['supply']} | "
            f"{'independent' if row['independent'] else 'derived — never a second witness'} | "
            f"{row['asserts']} |"
        )
    lines += [
        "",
        "## Joining on a subject means the subject must be one asset",
        "",
        "Four collectors name one host four ways — `alb-payments-01`, `payments-api`,",
        "`10.0.3.4:443`, `spiffe://bank.example/ns/payments/sa/api`. Grouping by the string",
        "each collector used would make those four subjects and no correlation would ever",
        "fire; merging by similarity would join two hosts. `subject_resolution` matches",
        "**exact keys the asset declares**, and refuses a key two assets claim.",
        "",
        "| Probe | Result |",
        "|---|---|",
        f"| Four spellings joined to one asset | {resolution['merges_all_spellings']} |",
        f"| Keys used | {', '.join(f'`{item}`' for item in resolution['schemes'])} |",
        f"| Ambiguous key refused, not resolved | {resolution['refuses_ambiguity']} |",
        f"| State | {resolution['state']} |",
        "",
        "## How two planes are joined",
        "",
        "`correlate(..., plane_facts=[...])` reads facts shaped as",
        '`{plane, subject, relation, statement, evidence_ids}`. Only two relations exist —',
        "`OBSERVED` and `ABSENT` — because anything richer would be a verdict this layer must",
        "not reach. Two rules read them:",
        "",
        "- **`MULTI_PLANE_AGREEMENT`** (level 2) — a change landed on a subject that two or",
        "  more *independent* planes describe. Agreement is what a correct estate looks like,",
        "  so it raises review priority and never suspicion of intent.",
        "- **`PLANE_CONTRADICTION`** (level 2) — one plane holds evidence for a subject and",
        "  another records it absent. That is a finding about the evidence (a scope or a",
        "  moment differs), never a compromise and never an accusation.",
        "",
        "Both stop at level 2. `SECURITY_INCIDENT` is still never assigned by this engine.",
        "Facts from a plane the engine does not know are counted as",
        "`unrecognised_plane_facts` rather than relabelled into a known plane, and a derived",
        f"plane ({', '.join(f'`{item}`' for item in document['derived_planes'])}) is cited but",
        "never counted as a witness — it is built from the planes it would otherwise",
        "corroborate.",
        "",
        "## What each plane cannot say",
        "",
    ]
    for row in document["planes"]:
        lines.append(f"### {row['label']}")
        lines.append("")
        lines.append(f"- **Asserts:** {row['asserts']}")
        lines.append(f"- **Cannot say:** {row['blind_spot']}")
        producers = ", ".join(
            f"`{item['ref']}`" + ("" if item["present"] else f" (absent: {item['reason']})")
            for item in row["producers"]
        )
        lines.append(f"- **Producer measured:** {producers}")
        measurement = row["measurement"]
        lines.append(
            f"- **Measured reading:** {measurement['status']} — {measurement['reason']}"
        )
        lines.append(f"- **Probe:** `{measurement['probe_statement']}`")
        lines.append("")
    lines += [
        "## Blind planes",
        "",
        (document["blind"] and ", ".join(f"`{item['id']}` — {item['why']}" for item in document["blind"]))
        or "None: every plane is both read and supplied in this build.",
        "",
        document["claim"] + ".",
        "",
        document["note"] + ".",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the register document")
    parser.add_argument("--print", dest="echo", action="store_true", help="print the document")
    args = parser.parse_args(argv)

    from shared_models.attack_planes import register

    document = render(register())
    if args.echo or not args.write:
        print(document)
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(document)
        print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
