"""Write the collector-family register as a document, from the measured register.

The document is generated rather than written so it cannot drift from the code: a
family's status is decided by importing its entrypoints (see
``shared_models/collector_families.py``), and this script only renders the result.
``scripts/tests/test_collector_families.py`` requires the committed file to equal a
fresh render.

    python scripts/gen_collector_families.py --write
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "bank-environment" / "105-collector-family-register.md"

STATUS_MEANING = {
    "SHIPPED": "every declared entrypoint imports and is callable",
    "PARTIAL": "some entrypoints resolve; the rest are named",
    "ABSENT": "nothing resolves — the family does not exist in this build",
}

INPUT_MEANING = {
    "LIVE": "reads the system itself over its own API or protocol",
    "INJECTED": "parses config, export or text an operator supplies",
    "STORED": "reads evidence another collector already wrote",
}


def render(document: dict) -> str:
    counts = document["counts"]
    lines = [
        "# Collector family register",
        "",
        "Generated by `scripts/gen_collector_families.py --write` from",
        "`shared_models/collector_families.py`. Do not edit by hand; regenerate and read",
        "the diff.",
        "",
        "Every collector family the product vision names, with the status this build",
        "**measures**. Status is computed by importing each family's declared entrypoints,",
        "so a family cannot be reported shipped without code behind it, and a family whose",
        "code only parses data an operator supplies is reported as exactly that.",
        "",
        "`production` is stricter than `shipped` and requires all three: the entrypoints",
        "import, the collector reads the system itself, and it reads the **customer's**",
        "estate rather than this platform's own. Nothing here is a coverage or maturity",
        "score; the numbers are counts of rows in each state.",
        "",
        "| Measure | Count |",
        "|---|---|",
        f"| Families in the register | {len(document['families'])} |",
        f"| Shipped (code exists) | {counts['SHIPPED']} |",
        f"| Partial | {counts['PARTIAL']} |",
        f"| Absent | {counts['ABSENT']} |",
        f"| **Production** (shipped, live, estate) | **{document['production']}** |",
        "",
        "## The families",
        "",
        "| Family | Status | Input | Scope | Strongest evidence | What it reads |",
        "|---|---|---|---|---|---|",
    ]
    for row in document["families"]:
        lines.append(
            f"| **{row['label']}** (`{row['id']}`) | {row['status']} | {row['input']} | "
            f"{row['scope']} | `{row['evidence']}` | {row['reads']} |"
        )
    lines += [
        "",
        "## Where the production gap is",
        "",
        document["production_gap_note"].capitalize() + ": "
        + ", ".join(f"`{family}`" for family in document["production_gap"])
        + ".",
        "",
        "## Each family's stated limit",
        "",
    ]
    for row in document["families"]:
        lines.append(f"### {row['label']}")
        lines.append("")
        lines.append(f"- **Status:** {row['status']} — {STATUS_MEANING[row['status']]}")
        lines.append(f"- **Input:** {row['input']} — {INPUT_MEANING[row['input']]}")
        lines.append(f"- **Scope:** {'the customer estate' if row['scope'] == 'ESTATE' else 'this platform itself'}")
        lines.append(f"- **Entrypoints measured:** {', '.join(f'`{item}`' for item in row['entrypoints']) or 'none'}")
        if row["missing"]:
            lines.append(f"- **Missing:** {', '.join(f'`{item}`' for item in row['missing'])}")
        lines.append(f"- **Limit:** {row['limit']}")
        if row["reason"]:
            lines.append(f"- **Why it is not there:** {row['reason']}")
        lines.append("")
    lines.append(document["claim"])
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the register document")
    parser.add_argument("--print", dest="echo", action="store_true", help="print the document")
    args = parser.parse_args(argv)

    from shared_models.collector_families import register

    document = render(register())
    if args.echo or not args.write:
        print(document)
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(document)
        print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
