def test_writing_stages_both_files_where_a_reviewer_can_read_them(tmp_path, capsys):
    written = generator.write(tmp_path)
    assert {path.name for path in written} == {"restore-drill.yml", "accuracy-gate.yml"}
    assert (tmp_path / "restore-drill.yml").read_text() == generator.render_restore_drill()
    capsys.readouterr()


def test_the_target_directory_is_the_one_github_reads():
    assert generator.WORKFLOW_DIR.name == "workflows"
    assert generator.WORKFLOW_DIR.parent.name == ".github"
