def test_the_drill_restores_into_a_named_recovery_database_and_never_the_source(drill):
    target = env(drill)["CRYPTOSCAN_RESTORE_TARGET_DB"]
    source = env(drill)["DATABASE_URL"]
    assert target != source
    assert "/restore" in target


def test_the_drill_backs_up_and_restores_in_the_same_run(drill):
    body = commands(drill)
    assert "--create-backup" in body
    assert "--out drill-receipt.json" in body
    assert "--history .drill-history.jsonl" in body


def test_the_drill_seeds_rows_before_measuring_them(drill):
    body = commands(drill)
    assert "restore_drill_seed.py" in body
    assert body.index("restore_drill_seed.py") < body.index("--create-backup")


def test_the_receipt_survives_a_failed_drill(drill):
    uploads = [step for step in steps(drill)
               if str(step.get("uses", "")).startswith("actions/upload-artifact")]
    assert uploads, "a drill with no artifact is a log line"
    assert uploads[0]["if"] == "always()"
    assert uploads[0]["with"]["if-no-files-found"] == "error"
    assert uploads[0]["with"]["retention-days"] == 365
    assert "drill-receipt.json" in str(uploads[0]["with"]["path"])


def test_the_published_key_is_a_real_fernet_key_protecting_nothing(drill):
    from cryptography.fernet import Fernet

    Fernet(env(drill)["BACKUP_ENCRYPTION_KEY"].encode())   # raises if it is not a usable key
    assert "not-a-production-secret" in env(drill)["BACKUP_SIGNING_SECRET"]


def test_the_estate_is_a_disposable_postgres_container(drill):
    assert "postgres" in drill["jobs"]["drill"]["services"]
    assert "@localhost" in env(drill)["DATABASE_URL"]


