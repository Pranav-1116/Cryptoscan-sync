def test_the_gate_compares_against_the_committed_baseline(gate):
    body = commands(gate)
    assert "--baseline docs/bank-environment/185-accuracy-ground-truth.json" in body
    assert "--gate" in body


def test_the_gate_fails_when_the_shortcut_starts_passing(gate):
    body = commands(gate)
    assert "--naive --gate" in body
    assert "exit 1" in body


def test_the_gate_runs_its_own_tests(gate):
    body = commands(gate)
    for test in ("scripts/tests/test_accuracy_ground_truth.py",
                 "services/cbom/tests/test_accuracy.py",
                 "services/cbom/tests/test_facts.py"):
        assert test in body


def test_the_gate_keeps_the_report_it_judged(gate):
    uploads = [step for step in steps(gate)
               if str(step.get("uses", "")).startswith("actions/upload-artifact")]
    assert uploads and uploads[0]["if"] == "always()"
    assert "accuracy-dashboard.md" in str(uploads[0]["with"]["path"])


def test_the_committed_baseline_exists_so_the_gate_has_something_to_compare():
    baseline = ROOT / "docs" / "bank-environment" / "185-accuracy-ground-truth.json"
    assert baseline.is_file(), "regenerate it with scripts/accuracy_ground_truth.py --json ..."
    assert '"rigorous"' in baseline.read_text()


