"""The evidence runs on a schedule, or it is a script nobody runs.

`scripts/restore_drill.py` and `scripts/accuracy_ground_truth.py` are the evidence; these are the
things that make it evidence about the repository rather than about the author's terminal. The
workflows are generated because `.github/workflows/` is the one path this build's token cannot
push, so they have to be reviewable, diffable and testable from somewhere else.

What is asserted is what makes them meaningful — not a golden string:

* each runs on a schedule and by hand;
* the drill restores into a named recovery database and never into the source, and the estate it
  restores carries rows (an empty estate restores to an empty estate and passes on nothing);
* the accuracy gate compares against the committed baseline and fails on a regression, and it
  fails if the `collector → CBOM` shortcut ever starts passing;
* the receipt survives a failed run, and the run's exit code is the drill's: no `|| true`, no
  `continue-on-error`;
* neither asks for a write permission.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[2]


def _generator():
    spec = importlib.util.spec_from_file_location(
        "pending_workflows", ROOT / "scripts" / "pending_workflows.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generator = _generator()


def triggers(document: dict) -> dict:
    """PyYAML reads the `on:` key as `True`, which is a YAML 1.1 truthiness trap."""
    return document[True] if True in document else document["on"]


def steps(document: dict) -> list[dict]:
    return document["jobs"][list(document["jobs"])[0]]["steps"]


def commands(document: dict) -> str:
    return "\n".join(str(step.get("run", "")) for step in steps(document))


def env(document: dict) -> dict:
    return document["jobs"][list(document["jobs"])[0]]["env"]


@pytest.fixture(scope="module")
def drill() -> dict:
    return yaml.safe_load(generator.render_restore_drill())


@pytest.fixture(scope="module")
def gate() -> dict:
    return yaml.safe_load(generator.render_accuracy_gate())


# --------------------------------------------------------------------------- #
# both are schedules, not documents
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize("name", ["restore-drill.yml", "accuracy-gate.yml"])
def test_each_workflow_is_generated_and_scheduled(name):
    body = generator.rendered()[name]
    assert body.startswith("# Generated by `scripts/pending_workflows.py")
    document = yaml.safe_load(body)
    assert triggers(document)["schedule"][0]["cron"] == (
        generator.DRILL_SCHEDULE if name == "restore-drill.yml"
        else generator.ACCURACY_SCHEDULE)
    assert "workflow_dispatch" in triggers(document)


@pytest.mark.parametrize("name", ["restore-drill.yml", "accuracy-gate.yml"])
def test_neither_asks_for_a_write_permission(name):
    assert yaml.safe_load(generator.rendered()[name])["permissions"] == {"contents": "read"}


@pytest.mark.parametrize("name", ["restore-drill.yml", "accuracy-gate.yml"])
def test_nothing_is_allowed_to_fail_quietly(name):
    for step in steps(yaml.safe_load(generator.rendered()[name])):
        assert step.get("continue-on-error") in (None, False), step.get("name")
        assert "|| true" not in str(step.get("run", "")), step.get("name")


