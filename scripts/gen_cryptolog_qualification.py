#!/usr/bin/env python3
"""Generate docs/cryptolog/11_QUALIFICATION_REPORT.md from the harness.

The report is deterministic (timings are per-run and stay out of the
document), so the committed file can be checked byte-identical like
CURRENT-STATE.md. Run: .venv/bin/python scripts/gen_cryptolog_qualification.py --write
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "services" / "cryptolog"),
                str(ROOT / "shared" / "shared_models")]

REPORT = ROOT / "docs" / "cryptolog" / "11_QUALIFICATION_REPORT.md"


def build_report() -> str:
    from cryptolog.qualification_suite import run_suite
    result = run_suite()
    lines = [
        "# CryptoLog qualification report",
        "",
        "<!-- GENERATED by scripts/gen_cryptolog_qualification.py — do not edit by hand. -->",
        "",
        "Phase 8 qualification over the SYNTHETIC event corpus. Every check ran",
        "against in-memory stores and the real event/integrity contracts. Synthetic",
        "results never qualify a real-environment act; the external acts below stay",
        "register-only — the platform never marks them done from inside the repo.",
        "",
        "## Corpus",
        "",
        f"- size: {result['corpus']['size']} events per check",
        f"- label: **{result['corpus']['label']}** (collector `synthetic-corpus`, `attributes.synthetic = true`)",
        "- timings: measured per harness run and deliberately kept out of this document",
        "",
        "## Checks",
        "",
        "| Check | Status | Detail |",
        "|---|---|---|",
    ]
    for check in result["checks"]:
        detail = check["detail"].replace("|", "/")
        lines.append(f"| {check['check']} | **{check['status']}** | {detail} |")
    lines += [
        "",
        "## Collector integration status",
        "",
        "A fixture, a connector definition or a passing adapter test is NOT support:",
        "status starts REGISTERED and only a named qualification with its evidence",
        "reference may record QUALIFIED. None has.",
        "",
        "| Adapter | Status |",
        "|---|---|",
    ]
    for row in result["collector_qualification"]:
        lines.append(f"| {row['adapter_id']} | {row['status']} |")
    lines += [
        "",
        "## External acts (register only — NOT done)",
        "",
        "| Act | Why external | Status |",
        "|---|---|---|",
    ]
    for row in result["external_acts"]:
        lines.append(f"| {row['act']} | {row['reason']} | {row['status']} |")
    lines += [
        "",
        "## Boundary",
        "",
        result["note"] + ".",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text = build_report()
    if args.write:
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(text)
        print(f"wrote {REPORT.relative_to(ROOT)}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
