#!/usr/bin/env python3
"""Render a soak evidence directory (from scripts/soak.py) as Markdown.

    python scripts/soak_report.py docs/soak-evidence/2026-09-23-staging > docs/soak-evidence/2026-09-23-staging/REPORT.md

Reads summary.json, cycles.jsonl, and — if present — burn_in_report.json and
load_test_*.txt in the same directory. Prints what the numbers are; it does
not grade them. The pass/fail criteria live in docs/burn-in.md.
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


import json
import sys
from pathlib import Path


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    d = Path(argv[1])
    s = json.loads((d / "summary.json").read_text())
    cycles = [json.loads(l) for l in (d / "cycles.jsonl").read_text().splitlines() if l.strip()]
    m = s["meta"]
    out: list[str] = []
    p = out.append

    p(f"# Soak evidence — {d.name}")
    p("")
    p(f"Generated by `scripts/soak_report.py` from `{d.as_posix()}` at {s['updated_at']}.")
    p("")
    p("| | |")
    p("|---|---|")
    p(f"| Target API | `{m['api']}` |")
    p(f"| Scan target per cycle | `{m['target']}` |")
    p(f"| Commit | `{m['git']}` |")
    p(f"| Started | {s['started_at']} |")
    p(f"| Last cycle | {s['updated_at']} |")
    p(f"| Elapsed | **{s['elapsed_hours']} h** ({s['cycles']} cycles, every {int(m['interval_s'])} s) |")
    p(f"| Cycles OK / failed | **{s['cycles_ok']} / {s['cycles_failed']}** |")
    if s.get("stopped_by"):
        p(f"| Stopped by | {s['stopped_by']} |")
    p("")

    p("## Pipeline")
    p("")
    sc = s["scans"]
    p(f"- Scans queued through Redis and completed by the worker: **{sc['completed']}** "
      f"(failed {sc['failed']}, timed out {sc['timed_out']})")
    p(f"- Job wall time (14 stages, demo repo): p50 {sc['wall_s_p50']} s, p95 {sc['wall_s_p95']} s, max {sc['wall_s_max']} s")
    ec = s["evidence_chain"]
    p(f"- Evidence chains verified intact: **{ec['verified']}**, broken: **{ec['broken']}** "
      f"({ec['records_total']} evidence records)")
    p("")

    p("## API")
    p("")
    ar = s["api_reads"]
    p(f"- {ar['count']} dashboard reads (stats, scans, findings, drift, jobs, monitor, scope, capabilities, readyz, metrics): "
      f"p50 {ar['ms_p50']} ms, p95 {ar['ms_p95']} ms, p99 {ar['ms_p99']} ms, max {ar['ms_max']} ms, 5xx: **{ar['errors_5xx']}**")
    sse = s["sse"]
    p(f"- SSE probes: {sse['probes']}, delivered frames: {sse['with_frames']}, errors: {sse['errors']}")
    p("")

    p("## Resources over time")
    p("")
    p("| process | RSS first | RSS last | RSS max | growth | fds first | fds last | fds max |")
    p("|---|---|---|---|---|---|---|---|")
    for name in ("api", "worker", "monitor"):
        r = s["rss_mb"].get(name) or {}
        f = s["fds"].get(name) or {}
        if r:
            p(f"| {name} | {r['first']} MB | {r['last']} MB | {r['max']} MB | {r['growth_pct']} % | "
              f"{f.get('first')} | {f.get('last')} | {f.get('max')} |")
    p("")
    if s.get("postgres_connections"):
        pc = s["postgres_connections"]
        p(f"- PostgreSQL connections: min {pc['min']}, max {pc['max']}")
    if s.get("postgres_last"):
        pl = s["postgres_last"]
        p(f"- PostgreSQL at last sample: {pl.get('size_mb')} MB, dead tuples {pl.get('dead_tuples')}, rows {pl.get('rows')}")
    if s.get("queue_depth"):
        q = s["queue_depth"]
        p(f"- Redis queue depth: max {q['max']}, last {q['last']}")
    if s.get("redis_last"):
        rl = s["redis_last"]
        p(f"- Redis at last sample: {rl.get('used_memory_mb')} MB, {rl.get('connected_clients')} clients")
    p("")

    if s["failure_counts"]:
        p("## Failures")
        p("")
        for step, n in sorted(s["failure_counts"].items(), key=lambda kv: -kv[1]):
            p(f"- `{step}`: {n}")
        p("")
        p("<details><summary>first 20 failure records</summary>")
        p("")
        shown = 0
        for c in cycles:
            for f in c.get("failures", []):
                p(f"- cycle {c['cycle']} {c['started_at']} `{f['step']}`: {f['why']}")
                shown += 1
                if shown >= 20:
                    break
            if shown >= 20:
                break
        p("")
        p("</details>")
        p("")

    # RSS trend: one row per ~N cycles so the table stays readable
    step = max(1, len(cycles) // 24)
    p("## RSS trend (sampled)")
    p("")
    p("| cycle | time | api MB | worker MB | monitor MB | pg conns | queue |")
    p("|---|---|---|---|---|---|---|")
    for c in cycles[::step] + ([cycles[-1]] if cycles and (len(cycles) - 1) % step else []):
        r = c.get("resources", {})
        p(f"| {c['cycle']} | {c['started_at'][11:19]} | {r.get('api', {}).get('rss_mb')} | {r.get('worker', {}).get('rss_mb')} | "
          f"{r.get('monitor', {}).get('rss_mb')} | {r.get('postgres', {}).get('connections')} | {r.get('redis', {}).get('queue_depth')} |")
    p("")

    bi = d / "burn_in_report.json"
    if bi.is_file():
        rep = json.loads(bi.read_text())
        p(f"## Integration burn-in (`scripts/burn_in.py --target all`, {rep.get('ran_at', '')[:19]})")
        p("")
        p("| target | status | detail |")
        p("|---|---|---|")
        for r in rep.get("results", []):
            p(f"| {r['target']} | **{r['status']}** | {r['detail']} |")
        p("")

    for lt in sorted(d.glob("load_test_*.txt")):
        try:
            res = json.loads(lt.read_text())
        except Exception as _handler_exc:
            logger.debug(
                "expected_exception_boundary",
                extra={"error_type": type(_handler_exc).__name__},
            )
            continue
        p(f"## Load test (`{lt.name}`)")
        p("")
        lat = res.get("latency_ms", {})
        p(f"- {res['requests']} requests in {res['duration_s']} s = {res['throughput_rps']} rps; errors {res['errors']} "
          f"({res['error_rate']:.2%}); 429s {res.get('throttled_429', 0)}")
        p(f"- latency p50 {lat.get('p50')} ms, p90 {lat.get('p90')} ms, p99 {lat.get('p99')} ms, max {lat.get('max')} ms")
        if res.get("throttled_429", 0) > res["requests"] * 0.5:
            p("- **Note:** most responses were 429. All virtual users share one identity, so the production "
              "per-identity rate limit (not server capacity) was the ceiling. Use distinct identities or "
              "API keys per virtual user to measure capacity.")
        p("")

    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
