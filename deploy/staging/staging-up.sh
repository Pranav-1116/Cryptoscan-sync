#!/usr/bin/env bash
# Bring up a production-shaped staging stack on one host, without Docker:
#
#   PostgreSQL 16 (real server, TCP, scram auth)   :55432
#   Redis 7      (real server)                     :56379
#   API  (uvicorn, ENVIRONMENT=production)         :8010
#   Worker (job queue consumer, Redis-backed)
#   Monitor daemon (24/7 watch-list, leader lease in Redis)
#
# Everything the production guard demands is set for real: Postgres (no
# SQLite), a random SECRET_KEY, a PBKDF2 admin hash, explicit CORS, docs off.
# This is the stack the soak (deploy/staging/soak.sh) runs against and the
# evidence in docs/soak-evidence/ is captured from.
#
# Usage:  deploy/staging/staging-up.sh            # start (idempotent)
#         deploy/staging/staging-up.sh status
#         deploy/staging/staging-up.sh down
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
STAGE="${CRYPTOSCAN_STAGING_DIR:-/tmp/cryptoscan-staging}"
PY="${PY:-$ROOT/.venv/bin/python}"
PGBIN="$("$PY" -c 'import pgserver, pathlib; print(pathlib.Path(pgserver.__file__).parent / "pginstall" / "bin")' 2>/dev/null || true)"
REDIS_BIN="${REDIS_SERVER:-$STAGE/bin/redis-server}"
REDIS_CLI="${REDIS_CLI:-$STAGE/bin/redis-cli}"
PG_PORT=55432
REDIS_PORT=56379
API_PORT=8010
ENV_FILE="$STAGE/staging.env"

mkdir -p "$STAGE/logs" "$STAGE/data" "$STAGE/run"

log() { printf '[staging] %s\n' "$*"; }

pythonpath() {
  find "$ROOT/services" "$ROOT/shared" -mindepth 1 -maxdepth 1 -type d | tr '\n' ':'
}

ensure_env() {
  if [[ -f "$ENV_FILE" ]]; then return; fi
  log "writing $ENV_FILE (secrets generated once, staging-only)"
  local secret admin_pw admin_hash webhook
  secret="$(openssl rand -hex 32)"
  admin_pw="St@ging-$(openssl rand -hex 8)"
  webhook="$(openssl rand -hex 24)"
  admin_hash="$(PYTHONPATH="$(pythonpath)" "$PY" - "$admin_pw" <<'PY'
import sys
from api.security.passwords import hash_password
print(hash_password(sys.argv[1]))
PY
)"
  cat > "$ENV_FILE" <<EOF
# generated by deploy/staging/staging-up.sh — staging only, never reuse
ENVIRONMENT=production
LOG_LEVEL=INFO
DOCS_ENABLED=false
COOKIE_SECURE=false
ALLOW_SQLITE=false
ALLOW_INSECURE_CORS=false
CORS_ORIGINS=http://127.0.0.1:3003
SECRET_KEY=$secret
ADMIN_USERNAME=admin
ADMIN_PASSWORD=
ADMIN_PASSWORD_HASH='$admin_hash'
STAGING_ADMIN_PASSWORD='$admin_pw'
GITHUB_WEBHOOK_SECRET=$webhook
DATABASE_URL=postgresql://cryptoscan:staging-only-pw@127.0.0.1:$PG_PORT/cryptoscan
REDIS_URL=redis://127.0.0.1:$REDIS_PORT/0
SCAN_JOB_QUEUE_KEY=cryptoscan:jobs:queue
CRYPTOSCAN_SNAPSHOT_DIR=$STAGE/data
SBOM_STORAGE_DIR=$STAGE/data/sboms
CRYPTOSCAN_SOURCE_ROOTS=$ROOT/demo
WORKSPACE_DIR=$STAGE/work
MAX_CONCURRENT_JOBS=2
EVENT_TAILER_SECONDS=2
CRYPTOSCAN_CVE_LIVE=0
CRYPTOSCAN_TLS_LIVE=0
CRYPTOSCAN_CLOUD_LIVE=0
EOF
}

load_env() { set -a; # shellcheck disable=SC1090
  source "$ENV_FILE"; set +a; export PYTHONPATH; PYTHONPATH="$(pythonpath)"; }

pg_up() {
  [[ -n "$PGBIN" ]] || { echo "pgserver not installed: $PY -m pip install pgserver"; exit 1; }
  if [[ ! -f "$STAGE/pg/PG_VERSION" ]]; then
    log "initdb"
    mkdir -p "$STAGE/pg"
    "$PY" - <<PY
import pgserver
pg = pgserver.get_server("$STAGE/pg", cleanup_mode=None)
pg.psql("create user cryptoscan with password 'staging-only-pw';")
pg.psql("create database cryptoscan owner cryptoscan;")
PY
    "$PGBIN/pg_ctl" -D "$STAGE/pg" stop -m fast >/dev/null 2>&1 || true
    cat >> "$STAGE/pg/postgresql.conf" <<EOF
listen_addresses = '127.0.0.1'
port = $PG_PORT
max_connections = 100
shared_buffers = 128MB
log_min_duration_statement = 500
log_line_prefix = '%m [%p] %u@%d '
EOF
    printf 'host all all 127.0.0.1/32 scram-sha-256\n' >> "$STAGE/pg/pg_hba.conf"
  fi
  if ! "$PGBIN/pg_isready" -h 127.0.0.1 -p $PG_PORT -q; then
    log "starting postgres :$PG_PORT"
    "$PGBIN/pg_ctl" -D "$STAGE/pg" -l "$STAGE/logs/postgres.log" -w start >/dev/null
  fi
  "$PGBIN/pg_isready" -h 127.0.0.1 -p $PG_PORT
}

redis_up() {
  [[ -x "$REDIS_BIN" ]] || { echo "redis-server not found at $REDIS_BIN"; exit 1; }
  if ! "$REDIS_CLI" -p $REDIS_PORT ping >/dev/null 2>&1; then
    log "starting redis :$REDIS_PORT"
    "$REDIS_BIN" --port $REDIS_PORT --bind 127.0.0.1 --daemonize yes \
      --dir "$STAGE/data" --dbfilename staging.rdb --appendonly yes \
      --logfile "$STAGE/logs/redis.log" --pidfile "$STAGE/run/redis.pid" \
      --maxmemory 256mb --maxmemory-policy noeviction >/dev/null
    sleep 0.5
  fi
  "$REDIS_CLI" -p $REDIS_PORT ping
}

migrate() {
  log "alembic upgrade head (postgres)"
  ( cd "$ROOT/services/database" && "$PY" -m alembic -c migrations/alembic.ini upgrade head ) \
    > "$STAGE/logs/migrate.log" 2>&1 || { tail -20 "$STAGE/logs/migrate.log"; exit 1; }
  ( cd "$ROOT/services/database" && "$PY" -m alembic -c migrations/alembic.ini current ) 2>/dev/null | tail -1
}

start_bg() { # name, command...
  local name="$1"; shift
  local pidfile="$STAGE/run/$name.pid"
  if [[ -f "$pidfile" ]] && kill -0 "$(cat "$pidfile")" 2>/dev/null; then
    log "$name already running (pid $(cat "$pidfile"))"; return
  fi
  log "starting $name"
  nohup "$@" >> "$STAGE/logs/$name.log" 2>&1 &
  echo $! > "$pidfile"
}

api_up() {
  start_bg api "$PY" -m uvicorn api.main:app --host 0.0.0.0 --port $API_PORT \
    --workers 1 --proxy-headers --forwarded-allow-ips='*' --no-access-log
  for _ in $(seq 1 40); do
    if curl -fsS "http://127.0.0.1:$API_PORT/readyz" >/dev/null 2>&1; then
      log "api ready"; return; fi
    sleep 0.5
  done
  echo "api did not become ready — $STAGE/logs/api.log:"; tail -30 "$STAGE/logs/api.log"; exit 1
}

worker_up()  { start_bg worker  "$PY" -m worker.main; }
monitor_up() { start_bg monitor "$PY" "$ROOT/scripts/run_monitor.py"; }

status() {
  load_env
  printf '%-10s %s\n' postgres "$("$PGBIN/pg_isready" -h 127.0.0.1 -p $PG_PORT 2>&1)"
  printf '%-10s %s\n' redis "$("$REDIS_CLI" -p $REDIS_PORT ping 2>&1)"
  for n in api worker monitor; do
    local pf="$STAGE/run/$n.pid"
    if [[ -f "$pf" ]] && kill -0 "$(cat "$pf")" 2>/dev/null; then printf '%-10s up (pid %s)\n' "$n" "$(cat "$pf")"; else printf '%-10s DOWN\n' "$n"; fi
  done
  curl -fsS "http://127.0.0.1:$API_PORT/readyz" 2>/dev/null | head -c 300; echo
}

down() {
  load_env || true
  for n in monitor worker api; do
    local pf="$STAGE/run/$n.pid"
    if [[ -f "$pf" ]]; then kill "$(cat "$pf")" 2>/dev/null || true; rm -f "$pf"; log "stopped $n"; fi
  done
  "$REDIS_CLI" -p $REDIS_PORT shutdown nosave >/dev/null 2>&1 || true
  "$PGBIN/pg_ctl" -D "$STAGE/pg" stop -m fast >/dev/null 2>&1 || true
  log "down"
}

case "${1:-up}" in
  up)
    ensure_env; load_env
    pg_up; redis_up; migrate; api_up; worker_up; monitor_up
    status
    log "admin password: see STAGING_ADMIN_PASSWORD in $ENV_FILE"
    ;;
  status) status ;;
  down) down ;;
  *) echo "usage: $0 [up|status|down]"; exit 2 ;;
esac
