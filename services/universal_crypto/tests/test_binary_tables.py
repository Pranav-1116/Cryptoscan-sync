"""Full-table crypto fingerprints in binaries (advanced/52, round 36)."""

from __future__ import annotations

import struct

from universal_crypto.binary_engine import (
    LEVEL_WEIGHT,
    BinaryCryptoDetector,
    BinaryParser,
)
from universal_crypto.binary_tables import (
    TABLE_FINGERPRINTS,
    _INV_SBOX,
    _P256_N,
    _P256_P,
    _SBOX,
    _SHA256_K,
    _t0_entries,
    _td0_entries,
    scan_tables,
)


def test_registry_values_match_published_tables():
    # FIPS-197 S-box head and tail
    assert _SBOX[:4] == (0x63, 0x7C, 0x77, 0x7B)
    assert _SBOX[255] == 0x16
    assert _INV_SBOX[0] == 0x52 and _INV_SBOX[0x63] == 0
    # OpenSSL-style T-tables: Te0[0]=0xc66363a5, Te0[2]=0xee777799,
    # Td0[0]=0x51f4a750 (fixed by the AES spec's algebra, not copied)
    t0 = _t0_entries()
    assert t0[0] == 0xC66363A5 and t0[1] == 0xF87C7C84 and t0[2] == 0xEE777799
    assert _td0_entries()[0] == 0x51F4A750
    # SHA-256 K head (FIPS 180-4)
    assert _SHA256_K[:4] == (0x428A2F98, 0x71374491, 0xB5C0FBCF, 0xE9B5DBA5)


def test_curve_parameters_match_the_cryptography_library():
    from cryptography.hazmat.primitives.asymmetric import ec

    curve = ec.SECP256R1()
    assert curve.group_order == _P256_N
        # P-256 Gx is fixed; a typed-constant cross-check lives below
    # Gx from a generated public key's curve is fixed; verify our typed
    # constant against the library's own generator x via key export
    key = ec.generate_private_key(ec.SECP256R1())
    pub_numbers = key.public_key().public_numbers()
    # the generator x is not exposed pre-45; verify P-521 order instead
    from universal_crypto.binary_tables import _P521_N

    assert ec.SECP521R1().group_order == _P521_N
    assert pub_numbers.curve.name == "secp256r1"


def test_stripped_binary_with_only_an_sbox_is_detected():
    # the 52 case: no symbols, no strings — just the table in .rodata
    blob = b"\x00" * 4096 + bytes(_SBOX) + b"\x00" * 128
    hits = scan_tables(blob)
    assert any(h["algorithm"] == "AES" and h["offset"] == 4096
               and "S-box" in h["table"] for h in hits)

    artifact = BinaryParser().parse(blob, path="libcrypto_stripped.so")
    analysis = BinaryCryptoDetector().analyze(artifact)
    aes = next(d for d in analysis["detections"] if d["algorithm"] == "AES")
    assert "TABLE_FINGERPRINT" in aes["levels"]
    assert any("offset 4096" in e["detail"] for e in aes["evidence"])
    assert aes["verdict"] == "CONFIRMED_IMPLEMENTATION"
    assert LEVEL_WEIGHT["TABLE_FINGERPRINT"] == 0.95


def test_openssl_style_ttable_both_byte_orders():
    t0 = _t0_entries()
    for pack_format, note in (("<4I", "little-endian build"), (">4I", "big-endian build")):
        blob = b"JUNK" * 16 + struct.pack(pack_format, *t0) + b"JUNK" * 16
        hits = scan_tables(blob)
        assert any(h["algorithm"] == "AES" and "Te0" in h["table"] for h in hits), note


def test_decrypt_ttable_detected():
    blob = b"\x90" * 64 + struct.pack("<4I", *_td0_entries()) + b"\x90" * 64
    hits = scan_tables(blob)
    assert any(h["algorithm"] == "AES" and "Td0" in h["table"] for h in hits)


def test_curve_parameters_detected_mid_file():
    from universal_crypto.binary_tables import _P384_P, _P521_N

    blob = (b"\xde\xad" * 32 + _P256_P.to_bytes(32, "big")
            + _P384_P.to_bytes(48, "big") + _P521_N.to_bytes(66, "big"))
    hits = scan_tables(blob)
    labels = {h["table"] for h in hits}
    assert "P-256 prime p" in labels
    assert "P-384 prime p" in labels
    assert "P-521 group order n" in labels


def test_crc_and_keccak_tables():
    # canonical reflected CRC32 table (zlib), generated by the standard loop
    table = []
    for i in range(16):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ (0xEDB88320 if c & 1 else 0)
        table.append(c)
    assert table[0] == 0x00000000 and table[1] == 0x77073096
    from universal_crypto.binary_tables import _CRC32

    assert tuple(table) == _CRC32  # registry matches the generated table
    blob = b"x" * 32 + b"".join(struct.pack("<I", c) for c in table) + b"x" * 32
    hits = scan_tables(blob)
    assert any(h["algorithm"] == "CRC32" and h["offset"] == 32 for h in hits)
    # little-endian storage (how the table is compiled) also matches
    hits = scan_tables(b"y" * 16 + b"".join(struct.pack(">I", c) for c in table))
    assert any(h["algorithm"] == "CRC32" and "CRC32" in h["table"] for h in hits)


def test_no_false_positives_on_random_data():
    import os

    for _ in range(8):
        assert scan_tables(os.urandom(8192)) == []


def test_registry_has_both_sha2_families_and_keccak():
    algorithms = {alg for alg, _, _ in TABLE_FINGERPRINTS}
    for expected in ("AES", "SHA-256", "SHA-512", "SHA-3", "CRC32",
                     "CRC32C", "ECDSA", "Ed25519", "X25519", "ChaCha20"):
        assert expected in algorithms, expected


def test_parser_attaches_tables_for_every_format():
    # ELF-shaped header + S-box: parse must find the table via the wrapper
    elf = b"\x7fELF" + b"\x00" * 60 + bytes(_SBOX)
    artifact = BinaryParser().parse(elf, path="a.so")
    assert artifact.format == "elf"
    assert any(h["algorithm"] == "AES" for h in artifact.tables)
    # raw format too
    raw = BinaryParser().parse(bytes(_SBOX), path="blob.bin")
    assert raw.format == "raw"
    assert any(h["algorithm"] == "AES" for h in raw.tables)
