"""Full-table crypto fingerprints for binaries (advanced/52, round 36).

The §7 engine's constant matching is an 8-byte prefix at the start of a
section slice — it misses the case report 52 actually cares about: a
*stripped, optimized, statically linked* binary with no symbols and no
version strings. What such a binary cannot hide is the tables real
implementations embed in ``.rodata``:

* the AES S-box / inverse S-box, and the T-tables OpenSSL-style builds
  generate instead of the plain S-box (both byte orders — the table is
  endian-dependent),
* the SHA-2 K- and IV-words (code constants are little-endian, spec
  documents big-endian; both are matched),
* the zlib / Castagnoli CRC32 polynomial tables,
* the Keccak/SHA-3 round-constant sequence,
* NIST curve domain parameters (P-256/P-384/P-521), the Ed25519 group
  order, and the Curve25519 prime.

A full-table hit is ``TABLE_FINGERPRINT`` evidence — one notch below a
known-implementation signature: the table proves an implementation (or
at minimum its data) is embedded, at a specific offset the operator can
verify. This module is pure and stdlib-only, like the rest of §7: no
disassembly, no execution (angr/Ghidra control-flow analysis stays the
open external-tooling item).

Values are generated from the specifications, not copied from any
implementation, so no source licensing touches the repository.
"""

from __future__ import annotations

from typing import Any

#: how many entries of a repeating table constitute a hit (a table's
#: first words are its signature; the tail words add no discriminating
#: power once the first four match)
_TABLE_HEAD = 16


def _be(value: int, width: int) -> bytes:
    return value.to_bytes(width, "big")


def _le(value: int, width: int) -> bytes:
    return value.to_bytes(width, "little")


def _table(values: tuple[int, ...], width: int, *, both_orders: bool = True) -> list[bytes]:
    count = max(1, _TABLE_HEAD // width)
    head = values[:count]
    out = [b"".join(_be(v, width) for v in head)]
    if both_orders:
        out.append(b"".join(_le(v, width) for v in head))
    return out


