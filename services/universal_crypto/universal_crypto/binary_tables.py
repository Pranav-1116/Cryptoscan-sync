# table values, from the specifications
# --------------------------------------------------------------------------- #

def _aes_sbox() -> tuple[int, ...]:
    """FIPS-197 substitution box (generated, not copied)."""
    p = q = 1
    box = [0] * 256
    while True:
        # multiply p by 3
        p = p ^ ((p << 1) & 0xFF) ^ (0x1B if p & 0x80 else 0)
        # divide q by 3
        q ^= (q << 1) & 0xFF
        q ^= (q << 2) & 0xFF
        q ^= (q << 4) & 0xFF
        if q & 0x80:
            q ^= 0x09
        x = q ^ ((q << 1) | (q >> 7)) ^ ((q << 2) | (q >> 6)) ^ ((q << 3) | (q >> 5)) ^ ((q << 4) | (q >> 4))
        box[p] = x & 0xFF ^ 0x63
        if p == 1:
            break
    box[0] = 0x63
    return tuple(box)


def _aes_inv_sbox() -> tuple[int, ...]:
    sbox = _aes_sbox()
    inv = [0] * 256
    for i, value in enumerate(sbox):
        inv[value] = i
    return tuple(inv)


_SBOX = _aes_sbox()
_INV_SBOX = _aes_inv_sbox()

#: OpenSSL-style T-table entry 0 (Te0[0] = 0xc66363a5, Td0[0] = 0x51f4a750):
#: xtime/S-box algebra over GF(2^8), fixed by the AES spec's MixColumns
#: matrix — generated by composing the s-box with the matrix columns.
def _t0_entries() -> tuple[int, ...]:
    def xtime(a: int) -> int:
        a <<= 1
        return (a ^ 0x1B) & 0xFF if a & 0x100 else a & 0xFF

    def mul(a: int, b: int) -> int:  # GF(2^8) multiply
        result = 0
        while b:
            if b & 1:
                result ^= a
            a = xtime(a)
            b >>= 1
        return result

    return tuple(
        (mul(_SBOX[i], 2) << 24) | (_SBOX[i] << 16) | (_SBOX[i] << 8) | mul(_SBOX[i], 3)
        for i in range(4)
    )


def _td0_entries() -> tuple[int, ...]:
    def xtime(a: int) -> int:
        a <<= 1
        return (a ^ 0x1B) & 0xFF if a & 0x100 else a & 0xFF

    def mul(a: int, b: int) -> int:
        result = 0
        while b:
            if b & 1:
                result ^= a
            a = xtime(a)
            b >>= 1
        return result

    return tuple(
        (mul(_INV_SBOX[i], 14) << 24) | (mul(_INV_SBOX[i], 9) << 16)
        | (mul(_INV_SBOX[i], 13) << 8) | mul(_INV_SBOX[i], 11)
        for i in range(4)
    )


