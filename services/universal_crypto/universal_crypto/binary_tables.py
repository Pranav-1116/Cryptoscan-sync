def _bytes_table(blob: bytes, algorithm: str, label: str) -> tuple[tuple[str, bytes, str], ...]:
    return ((algorithm, blob, label),)


def _build_registry() -> tuple[tuple[str, bytes, str], ...]:
    entries: list[tuple[str, bytes, str]] = []
    sbox_bytes = bytes(_SBOX[:32])
    inv_bytes = bytes(_INV_SBOX[:32])
    entries.append(("AES", sbox_bytes, "AES S-box (first 32 bytes)"))
    entries.append(("AES", inv_bytes, "AES inverse S-box (first 32 bytes)"))
    for order_name, words in (("Te0 (encrypt)", _t0_entries()), ("Td0 (decrypt)", _td0_entries())):
        for blob in _table(words, 4):
            entries.append(("AES", blob, f"AES T-table {order_name}"))
    for words, label in ((_SHA256_K, "SHA-256 K constants"), (_SHA256_IV, "SHA-256 IV")):
        for blob in _table(words, 4):
            entries.append(("SHA-256", blob, label))
    entries.append(("SHA-1", b"".join(_be(v, 4) for v in _SHA1_IV), "SHA-1 IV (incl. h4)"))
    entries.append(("MD5", b"".join(_le(v, 4) for v in _MD5_IV), "MD5 init (little-endian words)"))
    for words, label in ((_SHA512_K, "SHA-512 K constants"), (_SHA512_IV, "SHA-512 IV")):
        for blob in _table(words, 8):
            entries.append(("SHA-512", blob, label))
    for blob in _table(_KECCAK_RC, 8):
        entries.append(("SHA-3", blob, "Keccak round constants"))
    for words, alg, label in ((_CRC32, "CRC32", "CRC32 (zlib) polynomial table"),
                              (_CRC32C, "CRC32C", "CRC32C (Castagnoli) table")):
        for blob in _table(words, 4):
            entries.append((alg, blob, label))
    for value, width, alg, label in (
        (_P256_P, 32, "ECDSA", "P-256 prime p"),
        (_P256_N, 32, "ECDSA", "P-256 group order n"),
        (_P256_GX, 32, "ECDSA", "P-256 base point x"),
        (_P384_P, 48, "ECDSA", "P-384 prime p"),
        (_P384_N, 48, "ECDSA", "P-384 group order n"),
        (_P521_N, 66, "ECDSA", "P-521 group order n"),
        (_ED25519_L, 32, "Ed25519", "Ed25519 group order L"),
        (_X25519_P, 32, "X25519", "Curve25519 prime p"),
    ):
        entries.append((alg, _be(value, width), label))
    # ChaCha/Salsa text constant (already in the engine, kept here so the
    # table scan is the one complete registry)
    entries.append(("ChaCha20", b"expand 32-byte k", "ChaCha20/Salsa sigma constant"))
    return tuple(entries)


#: (algorithm, table-bytes, human label)
TABLE_FINGERPRINTS: tuple[tuple[str, bytes, str], ...] = _build_registry()

_TABLE_LOOKUP = [(algorithm, blob, label) for algorithm, blob, label in TABLE_FINGERPRINTS
                 if len(blob) >= 8]


def scan_tables(data: bytes, *, max_hits: int = 64) -> list[dict[str, Any]]:
    """Find full crypto tables anywhere in ``data``.

    Returns hits newest-stable first is not meaningful; output is sorted
    by (algorithm, offset) for deterministic reporting. Each hit carries
    the offset and label so an operator can verify it in the file.
    """
    hits: list[dict[str, Any]] = []
    seen: set[tuple[str, int]] = set()
    for algorithm, blob, label in _TABLE_LOOKUP:
        start = 0
        while len(hits) < max_hits:
            offset = data.find(blob, start)
            if offset < 0:
                break
            marker = (algorithm, offset)
            if marker not in seen:
                seen.add(marker)
                hits.append({
                    "algorithm": algorithm,
                    "table": label,
                    "offset": offset,
                    "length": len(blob),
                })
            start = offset + 1
    hits.sort(key=lambda hit: (hit["algorithm"], hit["offset"], hit["table"]))
    return hits
