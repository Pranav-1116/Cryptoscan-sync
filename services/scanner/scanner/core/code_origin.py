"""Classify a scanned file's origin so 10–50M-LOC estates can be triaged.

Findings are never dropped based on origin — a vulnerable cipher in a vendored
JAR is still in the inventory (and still a CBOM entry). The origin lets the
reviewer sort: ``source`` (hand-written, owned) vs ``test`` vs ``generated``
(stubs, protobuf, JAXB, jOOQ, minified) vs ``vendored`` (third-party checked
in) vs ``archive`` (findings extracted from JAR/WAR/EAR bytecode).

Detection is path-first, then a cheap header sniff of the first 2 KB.
"""

from __future__ import annotations

import re
from pathlib import Path

SOURCE = "source"
TEST = "test"
GENERATED = "generated"
VENDORED = "vendored"
ARCHIVE = "archive"

_ARCHIVE_SUFFIXES = (".jar", ".war", ".ear", ".aar", ".class", ".zip")

_VENDOR_DIRS = frozenset({
    "vendor", "vendors", "vendored", "third_party", "thirdparty", "third-party", "3rdparty", "3rd_party",
    "external", "externals", "extern", "node_modules", "bower_components", "jspm_packages", "pods",
    "carthage", "packages", "site-packages", "dist-packages", "libs", "jars", "ext", "contrib",
})
_GENERATED_DIRS = frozenset({
    "generated", "generated-sources", "generated-test-sources", "gen", "gen-java", "gen-src", "__generated__",
    "autogen", "auto-generated", "codegen", "build-gen", "target", "obj", ".generated", "genproto", "pb", "protogen",
})
_TEST_DIRS = frozenset({
    "test", "tests", "testing", "__tests__", "spec", "specs", "integration-test", "integration-tests",
    "integrationtest", "e2e", "testdata", "test_data", "fixtures", "mocks", "__mocks__", "benchmarks", "bench",
    "androidtest", "unittest", "unittests", "uitests", "cypress",
})

_GENERATED_FILE = re.compile(
    r"(?:\.pb\.(?:go|cc|h|swift|dart|rb)$|_pb2(?:_grpc)?\.py$|\.pb\.js$|_pb\.(?:js|ts|d\.ts)$|\.g\.(?:cs|dart|kt)$|"
    r"\.designer\.cs$|\.generated\.(?:cs|ts|js|swift|kt|java)$|_generated\.[a-z0-9]+$|\.min\.(?:js|css)$|"
    r"\.bundle\.js$|\.chunk\.js$|\.freezed\.dart$|\.gr\.dart$|\.mocks\.dart$|_mock\.go$|\.gen\.go$|_gen\.go$|"
    r"_string\.go$|\.ya?ml\.go$|\.jaxb\.java$|\.d\.ts$|package-lock\.json$|yarn\.lock$|Cargo\.lock$|Gemfile\.lock$|"
    r"go\.sum$|\.xcodeproj/|_flymake\.|\.min\.map$|\.js\.map$|\.css\.map$)",
    re.I,
)
_TEST_FILE = re.compile(
    r"(?:(?:^|[/\\])(?:test_[^/\\]+\.py|conftest\.py|[^/\\]*_test\.(?:go|py|rb|rs|c|cc|cpp|ex|exs)|"
    r"[^/\\]*(?:Test|Tests|IT|ITCase|Spec|TestCase)\.(?:java|kt|scala|groovy|cs|swift|php)|"
    r"[^/\\]*\.(?:test|spec)\.(?:[cm]?[jt]sx?|vue|svelte)|[^/\\]*_spec\.rb|[^/\\]*Tests?\.swift|[^/\\]*\.feature|"
    r"[^/\\]*(?:_|-)tests?\.(?:sh|bash|ps1|sql|php|lua|dart)|[^/\\]*\.t)$)",
    re.I,
)
_GENERATED_HEADER = re.compile(
    r"(?:@Generated\b|<auto-?generated\b|(?:auto-?|automatically |machine[ -])generated|do not (?:edit|modify)|"
    r"generated by (?:the )?(?:protocol buffer compiler|protoc|protoc-gen|swagger|openapi|openapi-generator|"
    r"swagger-codegen|jOOQ|wsimport|xjc|JAXB|Apache CXF|Thrift|Avro|ANTLR|JavaCC|Bison|flex|lex|yacc|Xtext|"
    r"MyBatis Generator|Hibernate Tools|Lombok|Dagger|Room|Realm|Moshi|kapt|ksp|EMF|Acceleo|JHipster|Yeoman|"
    r"Angular CLI|create-react-app|Vue CLI|Nx|Bazel|CMake|Gradle|Maven|go generate|stringer|mockgen|mockery|"
    r"gomock|wire|ent|sqlc|gqlgen|graphql-codegen|apollo|prisma|typeorm|sequelize|Entity Framework|T4|"
    r"Roslyn|protobuf-net|grpc|gRPC|Cap'n Proto|FlatBuffers|Cython|SWIG|pybind|f2py|ctypesgen|bindgen|cbindgen|"
    r"wasm-bindgen|uniffi|tonic|prost|serde_derive|Diesel|SeaORM|sqlx|Dart|build_runner|json_serializable|"
    r"freezed|retrofit|chopper|drift|floor|moor|hive|isar|objectbox|realm|Pigeon|flutter)\b|"
    r"this (?:file|code|class) (?:was|is|has been) (?:auto-?)?generated|generated code|code generated by|"
    r"Generated from [\w./-]+\.(?:proto|thrift|avsc|wsdl|xsd|idl|g4|jj|y|l|swagger|yaml|json)|"
    r"Any modifications (?:to this file )?will be (?:lost|overwritten)|changes (?:to this file )?may cause incorrect behavior)",
    re.I,
)


def _parts(rel: Path) -> tuple[str, ...]:
    return tuple(p.lower() for p in rel.parts[:-1])


def classify_origin(path: Path, repo_root: Path | None, head: str | None = None) -> str:
    """Return one of source|test|generated|vendored|archive for ``path``.

    ``head`` is the first ~2 KB of the file when the caller already has it (avoids a
    second read). Archives win over everything (their findings come from bytecode);
    vendored beats generated beats test — a generated stub under vendor/ is vendored,
    a test under generated/ is generated.
    """
    try:
        rel = path.relative_to(repo_root) if repo_root else path
    except ValueError:
        rel = path
    name = path.name.lower()
    suffix = path.suffix.lower()
    if suffix in _ARCHIVE_SUFFIXES or ".jar!" in str(rel) or ".war!" in str(rel) or ".ear!" in str(rel):
        return ARCHIVE
    dirs = _parts(rel)
    dirset = set(dirs)
    if dirset & _VENDOR_DIRS:
        # `lib`/`libs`/`ext` are also common hand-written module names; only treat as vendored
        # when they hold binaries/minified files or sit under a recognised vendor parent.
        strong = dirset & (_VENDOR_DIRS - {"libs", "jars", "ext", "contrib", "packages", "external", "externals", "extern"})
        if strong or suffix in (".jar", ".dll", ".so", ".min.js") or name.endswith(".min.js"):
            return VENDORED
        if dirset & {"external", "externals", "extern", "contrib"}:
            return VENDORED
    if dirset & _GENERATED_DIRS or _GENERATED_FILE.search(str(rel).replace("\\", "/")):
        return GENERATED
    if head is None:
        try:
            with open(path, "rb") as fh:
                head = fh.read(2048).decode("utf-8", errors="replace")
        except OSError:
            head = ""
    if head and _GENERATED_HEADER.search(head[:2048]):
        return GENERATED
    if dirset & _TEST_DIRS or _TEST_FILE.search(str(rel).replace("\\", "/")):
        return TEST
    if "src" in dirs:
        i = dirs.index("src")
        if len(dirs) > i + 1 and dirs[i + 1] in ("test", "androidtest", "integrationtest", "it", "testfixtures"):
            return TEST
    return SOURCE


def origin_summary(findings) -> dict[str, int]:
    """Count findings per origin (for scan summaries / CLI output)."""
    out: dict[str, int] = {}
    for f in findings:
        o = (getattr(getattr(f, "metadata", None), "code_origin", None) or SOURCE)
        out[o] = out.get(o, 0) + 1
    return out
