"""Origin classification: source / test / generated / vendored / archive."""
from pathlib import Path

import pytest

from scanner.core.code_origin import ARCHIVE, GENERATED, SOURCE, TEST, VENDORED, classify_origin, origin_summary

ROOT = Path("/repo")


@pytest.mark.parametrize(
    "rel, head, expected",
    [
        ("src/main/java/com/bank/pay/PinService.java", "package com.bank.pay;", SOURCE),
        ("core/payments/hsm_client.py", "import hsm", SOURCE),
        ("src/test/java/com/bank/pay/PinServiceTest.java", "package x;", TEST),
        ("pkg/crypto/aes_test.go", "package crypto", TEST),
        ("web/src/auth/login.spec.ts", "import {x}", TEST),
        ("tests/test_keys.py", "", TEST),
        ("vendor/github.com/x/y/cipher.go", "package y", VENDORED),
        ("third_party/bcprov/src/BC.java", "", VENDORED),
        ("web/node_modules/jsonwebtoken/sign.js", "", VENDORED),
        ("lib/ext/legacy/Crypto.java", "", SOURCE),  # bare lib/ext is too common a module name
        ("proto/gen/go/pay/pay.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.", GENERATED),
        ("api/client/model_key.py", "# coding: utf-8\n# Generated by OpenAPI Generator", GENERATED),
        ("app/target/classes/Foo.java", "", GENERATED),
        ("Forms/Main.Designer.cs", "", GENERATED),
        ("static/app.min.js", "!function(){}", GENERATED),
        ("libs/legacy-crypto-1.2.jar", None, ARCHIVE),
        ("deploy/app.ear!/lib/bc.jar!/org/bouncycastle/X.class", None, ARCHIVE),
        # a test under generated/ is generated; hand-written module named `ext` without binaries stays source
        ("generated/tests/FooTest.java", "", GENERATED),
        ("ext/Foo.java", "package ext;", SOURCE),
        ("src/main/java/com/bank/it/Router.java", "", SOURCE),
    ],
)
def test_classify(rel, head, expected):
    assert classify_origin(ROOT / rel, ROOT, head) == expected


def test_summary_counts(tmp_path):
    from scanner.registry.language_scanners import scan_file

    src = tmp_path / "src" / "main" / "java" / "A.java"
    src.parent.mkdir(parents=True)
    src.write_text('class A { void f() throws Exception { javax.crypto.Cipher.getInstance("AES/GCM/NoPadding"); } }\n')
    tst = tmp_path / "src" / "test" / "java" / "ATest.java"
    tst.parent.mkdir(parents=True)
    tst.write_text('class ATest { void f() throws Exception { java.security.MessageDigest.getInstance("MD5"); } }\n')
    findings = scan_file(src, tmp_path) + scan_file(tst, tmp_path)
    assert findings
    assert {f.metadata.code_origin for f in scan_file(src, tmp_path)} == {SOURCE}
    assert {f.metadata.code_origin for f in scan_file(tst, tmp_path)} == {TEST}
    summary = origin_summary(findings)
    assert summary[SOURCE] >= 1 and summary[TEST] >= 1


def test_pipeline_scans_test_dirs_by_default_and_can_exclude_them(tmp_path):
    from scanner.core.scanner import Scanner

    src = tmp_path / "src" / "main" / "java" / "A.java"
    src.parent.mkdir(parents=True)
    src.write_text('class A { void f() throws Exception { javax.crypto.Cipher.getInstance("AES/GCM/NoPadding"); } }\n')
    tst = tmp_path / "src" / "test" / "java" / "ATest.java"
    tst.parent.mkdir(parents=True)
    tst.write_text('class ATest { void f() throws Exception { java.security.MessageDigest.getInstance("MD5"); } }\n')
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules" / "x.js").write_text("require('crypto').createHash('md5')\n")

    result = Scanner().scan(root_path=tmp_path, target_type="LOCAL_DIRECTORY", target_location=str(tmp_path))
    assert result.statistics.findings_by_origin == {SOURCE: 1, TEST: 1}
    result = Scanner(exclude_test_dirs=True).scan(root_path=tmp_path, target_type="LOCAL_DIRECTORY", target_location=str(tmp_path))
    assert result.statistics.findings_by_origin == {SOURCE: 1}
