"""Lockfile parsers: each format yields canonical resolved rows, merges with
declared manifests (resolved version wins, declared spec kept), and never
raises on a malformed file."""

from __future__ import annotations

import json

from devsecops import sbom_lockfiles as lf
from devsecops import sbom_scan as sb


def _write(path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _by_name(rows):
    return {r["name"]: r for r in rows}


# ------------------------------------------------------------- package-lock -- #
def test_package_lock_v3_packages_map(tmp_path):
    pkg = tmp_path / "package-lock.json"
    _write(pkg, json.dumps({
        "lockfileVersion": 3,
        "packages": {
            "": {"name": "app", "dependencies": {"express": "^4.18.0"},
                 "devDependencies": {"jest": "^29.0.0"}},
            "node_modules/express": {"version": "4.19.2", "license": "MIT",
                                     "integrity": "sha512-x", "dependencies": {"accepts": "~1.3.8"}},
            "node_modules/accepts": {"version": "1.3.8", "license": "MIT"},
            "node_modules/jest": {"version": "29.7.0", "dev": True},
        },
        "dependencies": {},
    }))
    rows = _by_name(lf.parse_package_lock(pkg))
    assert set(rows) == {"express", "accepts", "jest"}
    assert rows["express"]["scope"] == "resolved"
    assert rows["express"]["direct"] is True
    assert rows["express"]["license"] == "MIT"
    assert rows["express"]["integrity"] == "sha512-x"
    assert rows["accepts"]["direct"] is False
    assert rows["accepts"].get("depends_on") is None
    assert rows["jest"]["direct"] is True  # devDependencies are direct too


def test_package_lock_v1_fallback(tmp_path):
    pkg = tmp_path / "package-lock.json"
    _write(pkg, json.dumps({
        "lockfileVersion": 1,
        "dependencies": {
            "express": {"version": "4.18.2", "requires": {"accepts": "~1.3.8"},
                        "dependencies": {"deduped-child": {"version": "1.0.0"}}},
        },
    }))
    rows = _by_name(lf.parse_package_lock(pkg))
    assert rows["express"]["version"] == "4.18.2"
    assert rows["express"]["direct"] is True
    assert rows["deduped-child"]["direct"] is False  # nested = transitive


# ---------------------------------------------------------------- yarn.lock -- #
def test_yarn_classic(tmp_path):
    lock = tmp_path / "yarn.lock"
    _write(lock, '''# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.23.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.23.0.tgz#abc"
  integrity sha512-babelhash
  dependencies:
    "@babel/types" "^7.23.0"
    semver "^6.3.1"

semver@^7.5.0:
  version "7.5.4"
  integrity sha512-semverhash
''')
    rows = _by_name(lf.parse_yarn_lock(lock))
    assert set(rows) == {"@babel/core", "semver"}
    core = rows["@babel/core"]
    assert core["version"] == "7.23.0"
    assert core["integrity"] == "sha512-babelhash"
    assert sorted(core["depends_on"]) == ["@babel/types", "semver"]
    assert rows["semver"]["version"] == "7.5.4"


