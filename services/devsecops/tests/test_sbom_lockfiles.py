def test_poetry_lock_with_pyproject_direct(tmp_path):
    _write(tmp_path / "pyproject.toml", '''[tool.poetry]
name = "demo"
[tool.poetry.dependencies]
python = "^3.11"
requests = "^2.31"
''')
    lock = tmp_path / "poetry.lock"
    _write(lock, '''[[package]]
name = "requests"
version = "2.31.0"
files = [{file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:aaa"}]
[package.dependencies]
certifi = ">=2017.4.17"

[[package]]
name = "certifi"
version = "2024.2.2"
files = [{file = "certifi-2024.2.2-py3-none-any.whl", hash = "sha256:bbb"}]
''')
    rows = _by_name(lf.parse_lockfile(lock))
    assert rows["requests"]["direct"] is True
    assert rows["certifi"]["direct"] is False
    assert rows["requests"]["integrity"] == "sha256:aaa"
    assert rows["requests"]["depends_on"] == ["certifi"]


def test_pipfile_lock(tmp_path):
    lock = tmp_path / "Pipfile.lock"
    _write(lock, json.dumps({
        "_meta": {"hash": {"sha256": "x"}},
        "default": {"flask": {"version": "==3.0.2", "hashes": ["sha256:fff"]}},
        "develop": {"pytest": {"version": "==8.1.1"}},
    }))
    rows = _by_name(lf.parse_pipfile_lock(lock))
    assert rows["flask"]["version"] == "3.0.2"
    assert rows["flask"]["integrity"] == "sha256:fff"
    # without a Pipfile beside it the parser cannot tell direct from transitive
    assert "direct" not in rows["pytest"]


# ----------------------------------------------------------------- Cargo.lock -- #
def test_cargo_lock_skips_workspace_root(tmp_path):
    _write(tmp_path / "Cargo.toml", '[package]\nname = "demo"\n[dependencies]\nring = "0.17"\n')
    _write(tmp_path / "Cargo.lock", '''version = 3

[[package]]
name = "demo"
version = "0.1.0"
dependencies = ["ring"]

[[package]]
name = "ring"
version = "0.17.8"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa11"
dependencies = ["untrusted"]

[[package]]
name = "untrusted"
version = "0.9.0"
checksum = "bb22"
''')
    rows = _by_name(lf.parse_lockfile(tmp_path / "Cargo.lock"))
    assert "demo" not in rows  # the project itself is not a dependency
    assert rows["ring"]["version"] == "0.17.8"
    assert rows["ring"]["direct"] is True
    assert rows["ring"]["integrity"] == "sha256:aa11"
    assert rows["untrusted"]["direct"] is False


