def test_malformed_lockfile_is_not_fatal(tmp_path):
    _write(tmp_path / "package-lock.json", "{not json")
    _write(tmp_path / "poetry.lock", "this is not toml [[[")
    _write(tmp_path / "go.sum", "\x00\x01binary")
