# --------------------------------------------------------- go.sum/.NET/gradle -- #
def test_go_sum_skips_gomod_lines(tmp_path):
    _write(tmp_path / "go.mod", "module m\n\ngo 1.21\n\nrequire github.com/golang-jwt/jwt/v5 v5.2.0\n")
    _write(tmp_path / "go.sum", '''github.com/golang-jwt/jwt/v5 v5.2.0 h1:aaa=
github.com/golang-jwt/jwt/v5 v5.2.0/go.mod h1:bbb=
golang.org/x/crypto v0.21.0 h1:ccc=
''')
    rows = lf.parse_lockfile(tmp_path / "go.sum")
    assert len(rows) == 2
    by = _by_name(rows)
    assert by["github.com/golang-jwt/jwt/v5"]["direct"] is True
    assert by["golang.org/x/crypto"]["direct"] is False
    assert by["golang.org/x/crypto"]["integrity"] == "h1:ccc="


