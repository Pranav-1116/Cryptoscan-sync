def test_pkcs1_rsa_private_key_is_read_without_reading_the_key_out():
    result = ek.detect_embedded_keys(_rsa_pem())
    assert result["private_keys"] == 1 and result["unencrypted_private_keys"] == 1
    row = result["keys"][0]
    assert (row["kind"], row["key_type"], row["key_bits"]) == ("private-key", "rsa", 1024)
    assert row["format"] == "pem" and row["detector"] == "pem" and row["encrypted"] is False
    assert row["detail"]["components"] == 9
    assert row["material_sha256"] == hashlib.sha256(_rsa_pkcs1()).hexdigest()


