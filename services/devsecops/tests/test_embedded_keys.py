"""Embedded key material: real structures, honest limits, and no key bytes out.

Fixtures are built byte by byte with the small DER/armour builders below, so the
reader is exercised against structures it was written for. One test scans a real
key generated by ``openssl`` when that binary is on the box, and one asserts the
thing that matters most: the report never contains the key material itself.
"""
