def _elf_with(blob: bytes) -> bytes:
    """An ELF64 whose .rodata carries the given bytes (built by hand, no compiler)."""
    shstrtab = b"\x00.text\x00.rodata\x00.shstrtab\x00"
    text, rodata = b"\x90" * 32, blob
    sections = [
        {"name": 1, "type": 1, "flags": 6, "data": text},
        {"name": 7, "type": 1, "flags": 2, "data": rodata},
        {"name": 15, "type": 3, "flags": 0, "data": shstrtab},
    ]
    headers, payload = b"", b""
    for section in sections:
        headers += struct.pack("<IIQQQQIIQQ", section["name"], section["type"], section["flags"],
                               0, 64 + 64 * len(sections) + len(payload), len(section["data"]),
                               0, 0, 1, 0)
        payload += section["data"]
    elf = struct.pack("<16sHHIQQQIHHHHHH", b"\x7fELF\x02\x01\x01\x00" + b"\x00" * 8, 3, 0x3E,
                      1, 0, 0, 64, 0, 64, 64, 0, 64, len(sections), len(sections) - 1)
    elf += headers + payload
    return elf


def _write(path: Path, blob: bytes) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(blob)
    return path


