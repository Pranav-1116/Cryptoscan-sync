# --------------------------------------------------------------- DER glue --- #
def _tlv(tag: int, content: bytes) -> bytes:
    if len(content) < 0x80:
        return bytes([tag, len(content)]) + content
    size = len(content)
    length = b""
    while size:
        length = bytes([size & 0xFF]) + length
        size >>= 8
    return bytes([tag, 0x80 | len(length)]) + length + content


def _seq(*items: bytes) -> bytes:
    return _tlv(0x30, b"".join(items))


def _set(*items: bytes) -> bytes:
    return _tlv(0x31, b"".join(items))


def _integer(value: int) -> bytes:
    if value == 0:
        return _tlv(0x02, b"\x00")
    raw = value.to_bytes((value.bit_length() + 7) // 8, "big")
    if raw[0] & 0x80:
        raw = b"\x00" + raw
    return _tlv(0x02, raw)


def _integer_bytes(raw: bytes) -> bytes:
    if raw[0] & 0x80:
        raw = b"\x00" + raw
    return _tlv(0x02, raw)


def _octet(data: bytes) -> bytes:
    return _tlv(0x04, data)


def _bit_string(data: bytes) -> bytes:
    return _tlv(0x03, b"\x00" + data)


def _utf8(text: str) -> bytes:
    return _tlv(0x0C, text.encode("utf-8"))


def _utc(text: str) -> bytes:
    return _tlv(0x17, text.encode("ascii"))


def _ctx(tag: int, data: bytes) -> bytes:
    return _tlv(0xA0 | tag, data)


def _oid(dotted: str) -> bytes:
    parts = [int(part) for part in dotted.split(".")]
    body = bytearray([parts[0] * 40 + parts[1]])
    for value in parts[2:]:
        chunk = [value & 0x7F]
        value >>= 7
        while value:
            chunk.insert(0, 0x80 | (value & 0x7F))
            value >>= 7
        body.extend(chunk)
    return _tlv(0x06, bytes(body))


def _pem(label: str, der: bytes, *, headers: bytes = b"") -> bytes:
    body = base64.encodebytes(der).replace(b"\n", b"")
    lines = b"\n".join(body[i:i + 64] for i in range(0, len(body), 64))
    head = b""
    if headers:
        head = headers + b"\n"
    return (b"-----BEGIN " + label.encode() + b"-----\n" + head + lines
            + b"\n-----END " + label.encode() + b"-----\n")


# key material that is not a repeat of one byte — a real key never is, and the
# detector treats long runs as placeholders
def _pseudo(seed: bytes, size: int) -> bytes:
    out = b""
    counter = 0
    while len(out) < size:
        out += hashlib.sha256(seed + counter.to_bytes(4, "big")).digest()
        counter += 1
    return out[:size]


# ------------------------------------------------------------ key fixtures --- #
MODULUS = b"\x80" + _pseudo(b"modulus", 127)     # 1024-bit, high bit set
EXPONENT = b"\x01\x00\x01"                    # 65537
PRIVATE_EXPONENT = _pseudo(b"private-exponent", 128)


def _rsa_pkcs1(private: bool = True) -> bytes:
    if not private:
        return _seq(_integer_bytes(MODULUS), _integer_bytes(EXPONENT))
    return _seq(_integer(0), _integer_bytes(MODULUS), _integer_bytes(EXPONENT),
                _integer_bytes(PRIVATE_EXPONENT), _integer_bytes(_pseudo(b"rsa-p", 64)),
                _integer_bytes(_pseudo(b"rsa-q", 64)), _integer_bytes(_pseudo(b"rsa-dp", 64)),
                _integer_bytes(_pseudo(b"rsa-dq", 64)), _integer_bytes(_pseudo(b"rsa-inv", 64)))


def _rsa_pkcs8() -> bytes:
    return _seq(_integer(0), _seq(_oid("1.2.840.113549.1.1.1"), _tlv(0x05, b"")),
                _octet(_rsa_pkcs1()))


def _rsa_pkcs8_encrypted() -> bytes:
    return _seq(_seq(_oid("1.2.840.113549.1.5.13"),
                     _seq(_seq(_oid("1.2.840.113549.1.5.12"), _octet(_pseudo(b"pbkdf-salt", 8)),
                               _integer(2048)),
                          _seq(_oid("2.16.840.1.101.3.4.1.42"), _octet(_pseudo(b"aes-iv", 16))))),
                _octet(_pseudo(b"encrypted-body", 1280)))


def _ec_sec1() -> bytes:
    return _seq(_integer(1), _octet(_pseudo(b"ec-private", 32)),
                _ctx(0, _oid("1.2.840.10045.3.1.7")),
                _ctx(1, _bit_string(b"\x04" + _pseudo(b"ec-public", 64))))


def _spki_rsa() -> bytes:
    return _seq(_seq(_oid("1.2.840.113549.1.1.1"), _tlv(0x05, b"")),
                _bit_string(_seq(_integer_bytes(MODULUS), _integer_bytes(EXPONENT))))


def _name(common_name: str) -> bytes:
    return _seq(_set(_seq(_oid("2.5.4.3"), _utf8(common_name))))


def _certificate() -> bytes:
    extensions = _tlv(0xA3, _seq(
        _seq(_oid("2.5.29.19"), _tlv(0x01, b"\xff"), _octet(_seq(_tlv(0x01, b"\xff")))),
        _seq(_oid("2.5.29.15"), _tlv(0x01, b"\xff"), _octet(_tlv(0x03, b"\x00\x06"))),
        _seq(_oid("2.5.29.37"), _octet(_seq(_oid("1.3.6.1.5.5.7.3.1")))),
    ))
    tbs = _seq(
        _ctx(0, _integer(2)),
        _integer(0x6C455F),
        _seq(_oid("1.2.840.10045.4.3.2")),
        _name("acme-test-root"),
        _seq(_utc("260101000000Z"), _utc("360101000000Z")),
        _name("acme-test-root"),
        _seq(_seq(_oid("1.2.840.10045.2.1"), _oid("1.2.840.10045.3.1.7")),
             _bit_string(b"\x04" + _pseudo(b"cert-public", 64))),
        extensions,
    )
    return _seq(tbs, _seq(_oid("1.2.840.10045.4.3.2")), _bit_string(b"\x30\x06" + b"\x02" * 8))


def _csr() -> bytes:
    cri = _seq(_integer(0), _name("csr-test"),
               _seq(_seq(_oid("1.2.840.10045.2.1"), _oid("1.2.840.10045.3.1.7")),
                    _bit_string(b"\x04" + _pseudo(b"csr-public", 64))))
    return _seq(cri, _seq(_oid("1.2.840.10045.4.3.2")), _bit_string(b"\x30\x06" + b"\x07" * 8))


def _pkcs12(bags: bool = True) -> bytes:
    inner = _seq(_oid("1.2.840.113549.1.7.6"), _ctx(0, _octet(_pseudo(b"pkcs7", 32))))
    return _seq(_integer(3),
                _seq(_oid("1.2.840.113549.1.7.1"), _ctx(0, _octet(inner))),
                _seq(_seq(_oid("1.2.840.113549.1.5.12"), _octet(_pseudo(b"p12-salt", 8)), _integer(2048)),
                     _octet(_pseudo(b"p12-hash", 20)), _integer(2048)),
                _tlv(0x30, _seq(_oid("1.2.840.113549.1.12.10.1.2"))) if bags else b"")


def _java_utf(text: str) -> bytes:
    raw = text.encode("utf-8")
    return struct.pack(">H", len(raw)) + raw


def _jks() -> bytes:
    cert = _certificate()
    entry_key = (struct.pack(">I", 1) + struct.pack(">q", 1_700_000_000_000)
                 + _java_utf("server-key") + struct.pack(">I", 96) + _pseudo(b"jks-protected", 96))
    entry_cert = (struct.pack(">I", 2) + _java_utf("acme-test-root") + _java_utf("X.509")
                  + struct.pack(">I", len(cert)) + cert)
    return (b"\xfe\xed\xfe\xed" + struct.pack(">I", 2) + struct.pack(">I", 2)
            + entry_key + entry_cert)


def _ssh_string(data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + data


def _openssh_private(*, encrypted: bool = False) -> bytes:
    public = _ssh_string(b"ssh-ed25519") + _ssh_string(_pseudo(b"openssh-public", 32))
    private = (struct.pack(">I", 0x0BADF00D) * 2 + _ssh_string(b"ssh-ed25519")
               + _ssh_string(_pseudo(b"openssh-public", 32)) + _ssh_string(_pseudo(b"openssh-secret", 64))
               + _ssh_string(b"acme@fleet"))
    cipher = b"aes256-ctr" if encrypted else b"none"
    kdfoptions = (struct.pack(">I", 12) + _pseudo(b"bcrypt-salt", 8) + struct.pack(">I", 16)
                  if encrypted else b"")
    return (b"openssh-key-v1\x00" + _ssh_string(cipher) + _ssh_string(b"bcrypt" if encrypted
                                                                     else b"none")
            + (kdfoptions if encrypted else _ssh_string(b""))
            + _ssh_string(struct.pack(">I", 1)) + _ssh_string(public)
            + _ssh_string(private if not encrypted else _pseudo(b"encrypted-section", 32)))


def _putty_private() -> bytes:
    return textwrap.dedent("""\
        PuTTY-User-Key-File-2: ssh-rsa
        Encryption: aes256-cbc
        Comment: acme provisioning key
        Public-Lines: 3
        AAAAB3NzaC1yc2EAAAADAQABAAAAgQ
        """).encode()


def _ssh_public_line() -> bytes:
    blob = _ssh_string(b"ssh-ed25519") + _ssh_string(_pseudo(b"ssh-public-blob", 32))
    return b'ssh-ed25519 ' + base64.b64encode(blob) + b" acme@fleet\n"


def _pgp_secret_armour(*, usage: int = 254, corrupt: bool = False) -> bytes:
    modulus = struct.pack(">H", 1024) + b"\x80" + _pseudo(b"pgp-modulus", 127)
    exponent = struct.pack(">H", 17) + b"\x01\x00\x01"
    body = (b"\x04" + struct.pack(">I", 1_700_000_000) + b"\x01" + modulus + exponent
            + bytes([usage]) + _pseudo(b"pgp-s2k", 16))
    payload = b"\xc5" + bytes([len(body) & 0xFF]) + body
    checksum = base64.b64encode(struct.pack(">I", ek._crc24(payload))[1:])
    if corrupt:
        payload = payload[:-1] + bytes([payload[-1] ^ 0xFF])   # damaged after the checksum
    encoded = base64.b64encode(payload)
    lines = b"\n".join(encoded[index:index + 64] for index in range(0, len(encoded), 64))
    return (b"-----BEGIN PGP PRIVATE KEY BLOCK-----\n\n" + lines
            + b"\n=" + checksum + b"\n-----END PGP PRIVATE KEY BLOCK-----\n")


def _rsa_pem(*, label: bytes = b"RSA PRIVATE KEY", prefix: bytes = b"",
             headers: bytes = b"") -> bytes:
    der = _rsa_pkcs1() if label != b"PRIVATE KEY" else _rsa_pkcs8()
    return prefix + _pem(label.decode(), der, headers=headers)


